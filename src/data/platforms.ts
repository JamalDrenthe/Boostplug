export const QUALITY_MULTIPLIERS: Record<string, number> = {
  standard: 1,
  premium: 1.5,
};

export function formatPrice(price: number, currency: Currency): string {
  const symbol = currency === 'EUR' ? '€' : '£';
  return `${symbol}${price.toFixed(2)}`;
}

export function calculateStreamPrice(
  basePrice: number,
  quantity: number,
  quality: string
): number {
  const multiplier = QUALITY_MULTIPLIERS[quality] || 1;
  return basePrice * quantity * multiplier;
}

export function calculateReviewPrice(
  pricePerItem: Record<Currency, number>,
  quantity: number,
  currency: Currency
): number {
  return pricePerItem[currency] * quantity;
}
